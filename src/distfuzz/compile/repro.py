"""Turn a compile-track program into a standalone script (plain PyTorch, no distfuzz imports).

    python -m distfuzz.compile repro min_3.json --out repro.py
    torchrun --nproc-per-node 4 repro.py

The helpers the script needs (input construction, the module track's model) are copied in as source.
"""

import argparse
import inspect
import json

from distfuzz.compile import module as M
from distfuzz.compile.prog import build_source
from distfuzz.dtensor import runtime as RT

OP_TEMPLATE = """# Generated by distfuzz.compile from a fuzzer program. Run: torchrun --nproc-per-node {world} {name}
import math

import torch
import torch.distributed as dist
import torch.nn.functional as F
from torch.distributed.device_mesh import init_device_mesh
from torch.distributed.tensor import DTensor, Partial, Replicate, Shard, distribute_tensor

dist.init_process_group("gloo")
rank = dist.get_rank()
mesh = init_device_mesh("cpu", {mesh_shape})

DTYPES = {dtypes}

{gen_full}

{partial_pieces}

{parse_pl}


def make(spec, distributed):
    T = gen_full(spec)
    if not distributed:
        return T.clone().requires_grad_() if spec.get("rg") else T.clone()
    pls = [parse_pl(p) for p in spec["pl"]]
    pdims = [d for d, p in enumerate(pls) if p.is_partial()]
    local_full = T
    if pdims:
        coord = mesh.get_coordinate()
        n, idx = 1, 0
        for d in pdims:
            idx = idx * mesh.size(d) + coord[d]
            n *= mesh.size(d)
        local_full = partial_pieces(T, n, pls[pdims[0]].reduce_op, spec["seed"] + 7919)[idx]
    repl = [Replicate() if p.is_partial() else p for p in pls]
    tmp = distribute_tensor(local_full, mesh, repl, src_data_rank=None)
    dt = DTensor.from_local(tmp.to_local(), mesh, pls, run_check=False, shape=T.shape, stride=T.stride())
    return dt.detach().requires_grad_() if spec.get("rg") else dt


def R(x, pls):
    if isinstance(x, DTensor):
        return x.redistribute(x.device_mesh, pls).clone()
    return x.clone()


def SETITEM(x, idx, y):
    x[idx] = y
    return x


def _d(x):
    return x.detach() if isinstance(x, torch.Tensor) else x


{src}
INPUTS = {inputs}
ARGS = {args}
OUTS = {outs}
BW = {bws}


def run(fn, distributed):
    ins = [make(INPUTS[j], distributed) for j in ARGS]
    out = list(fn(*ins))
    for t in BW:
        if t in OUTS and out[OUTS.index(t)].requires_grad:
            out[OUTS.index(t)].sum().backward()
    grads = [x.grad for x in ins]
    full = lambda v: v.full_tensor() if isinstance(v, DTensor) else v  # noqa: E731
    return [full(v) for v in out], [full(g) if g is not None else None for g in grads], out


ref, ref_g, _ = run(prog_fn, False)
eager, eager_g, eager_raw = run(prog_fn, True)
compiled_fn = torch.compile(prog_fn, backend={backend!r}, fullgraph={fullgraph!r}, dynamic={dynamic!r})
try:
    comp, comp_g, comp_raw = run(compiled_fn, True)
except Exception as e:
    print(f"rank {{rank}}: compiled raised {{type(e).__name__}}: {{str(e).splitlines()[0][:300]}}")
    raise SystemExit(1)


def same(a, b):
    if not isinstance(a, torch.Tensor) or not isinstance(b, torch.Tensor):
        return a is b
    return a.shape == b.shape and a.dtype == b.dtype and torch.allclose(a.double(), b.double(), 1e-4, 1e-4, True)


if rank == 0:
    for name, r, e, c, er, cr in zip(OUTS, ref, eager, comp, eager_raw, comp_raw):
        pe = getattr(er, "placements", None)
        pc = getattr(cr, "placements", None)
        print(f"{{name}}: eager==ref {{same(r, e)}}  compiled==ref {{same(r, c)}}  placements eager={{pe}} compiled={{pc}}")
        if not same(r, c):
            print("  ref     ", r)
            print("  compiled", c)
    for k, (r, e, c) in enumerate(zip(ref_g, eager_g, comp_g)):
        if r is not None:
            print(f"grad of arg {{k}}: eager==ref {{same(r, e)}}  compiled==ref {{same(r, c)}}")
dist.destroy_process_group()
"""

MODULE_TEMPLATE = """# Generated by distfuzz.compile from a module-track program. Run: torchrun --nproc-per-node {world} {name}
import copy
import re

import torch
import torch.distributed as dist
import torch.nn as nn
import torch.nn.functional as F
from torch.distributed.device_mesh import init_device_mesh

dist.init_process_group("gloo")
rank = dist.get_rank()
meshes = {{"1d": init_device_mesh("cpu", ({world},))}}
if {world} == 4:
    meshes["2d"] = init_device_mesh("cpu", (2, 2), mesh_dim_names=("dp", "tp"))

PROG = {prog}

{helpers}

base = build(PROG)
res = {{}}
for leg in ("ref", "eager", "compiled"):
    torch._dynamo.reset()
    m = copy.deepcopy(base)
    if leg != "ref":
        m = parallelize(PROG, m, meshes, leg == "compiled")
    losses = []
    train(PROG, m, make_opt(PROG, m.parameters()), False, losses)
    res[leg] = (losses, full_params(m))
if rank == 0:
    for leg in res:
        print(leg, "losses", res[leg][0])
    for n, p in res["ref"][1].items():
        e, c = res["eager"][1][n], res["compiled"][1][n]
        print(n, "eager==ref", torch.allclose(p, e, 1e-4, 1e-5), "compiled==ref", torch.allclose(p, c, 1e-4, 1e-5),
              "max|compiled-eager|", float((c - e).abs().max()))
dist.destroy_process_group()
"""


def op_repro(prog, name="repro.py"):
    src, fargs, outs, bws = build_source(prog)
    cfg = prog["cfg"]
    dyn = {"static": False, "dynamic": True, "mark": None}[cfg["dynamic"]]
    return OP_TEMPLATE.format(
        world=4,
        name=name,
        mesh_shape=(4,) if prog["mesh"] == "1d" else (2, 2),
        dtypes="{" + ", ".join(f"{k!r}: torch.{str(v).split('.')[-1]}" for k, v in RT.DTYPES.items()) + "}",
        gen_full=inspect.getsource(RT.gen_full),
        partial_pieces=inspect.getsource(RT.partial_pieces),
        parse_pl=inspect.getsource(RT.parse_pl),
        src=src,
        inputs=json.dumps(prog["inputs"]),
        args=[j for _, j in fargs],
        outs=outs,
        bws=bws,
        backend=cfg["backend"],
        fullgraph=cfg["fullgraph"],
        dynamic=dyn,
    )


def module_repro(prog, name="repro.py"):
    parts = [
        M.RMS,
        M.Block,
        M.Net,
        M.build,
        M.batch,
        M.tp_plan,
        M.compile_kw,
        M.parallelize,
        M.make_opt,
        M.canon,
        M.full_params,
        M.full_val,
        M.train,
    ]
    helpers = "\n\n".join(inspect.getsource(p) for p in parts)
    p = {k: v for k, v in prog.items() if k in ("track", "mesh", "model", "cfg")}
    return MODULE_TEMPLATE.format(world=4, name=name, prog=repr(p), helpers=helpers)


def write_repro(prog, path):
    import os

    text = module_repro(prog, os.path.basename(path)) if prog.get("track") == "module" else op_repro(prog)
    with open(path, "w") as f:
        f.write(text)
    return path


def main(argv=None):
    ap = argparse.ArgumentParser(prog="distfuzz.compile repro")
    ap.add_argument("program", help="a min_*.json, or a findings/failing .jsonl with --index")
    ap.add_argument("--index", type=int, default=0)
    ap.add_argument("--out", default="repro.py")
    a = ap.parse_args(argv)
    if a.program.endswith(".jsonl"):
        rec = [json.loads(line) for line in open(a.program)][a.index]
    else:
        rec = json.load(open(a.program))
    print(write_repro(rec.get("prog", rec), a.out))


if __name__ == "__main__":
    main()
